/*
Operadores de comparação
> maior que; >= maior ou igual a
< menor que; <= menor ou igual a
== igualdade (valor); === igualdade estrita (valor e tipo)
!= diferente (valor); !== diferente estrito (valor e tipo)
*/
let comp = 10 > 5;
console.log(comp);
comp = 10 >= 5
console.log(comp);
comp = 10 >= 10
console.log(comp);
comp = 10 < 5;
console.log(comp);
comp = 10 <= 5
console.log(comp);
comp = 10 <= 10
console.log(comp);

